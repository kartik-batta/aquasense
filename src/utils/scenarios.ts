/**
 * Generates a randomized scenario while preserving the mathematical VOI tipping dynamic
 */
export function generateRandomScenario(seedBudget: number = 3300, sensorBudget: number = 1): Scenario {
  const base = PRESET_SCENARIOS[0];
  const newZones = base.zones.map((z) => {
    // Add minor randomized variation
    const deltaMean = Math.round((Math.random() - 0.5) * 60);
    const mean = Math.max(200, z.estimated_water_need_mean + deltaMean);
    const std = Math.max(30, Math.round(z.estimated_water_need_std * (0.9 + Math.random() * 0.2)));
    const groundTruth = Math.round(normalRandom(mean, std));

    return {
      ...z,
      estimated_water_need_mean: mean,
      estimated_water_need_std: std,
      hidden_ground_truth_need: groundTruth,
      battery_pct: Math.min(100, Math.max(45, Math.round(z.battery_pct + (Math.random() - 0.5) * 10))),
    };
  });

  return {
    ...base,
    id: `custom_seed_${Date.now()}`,
    name: 'Dynamic Regional Water System',
    totalWaterBudget: seedBudget,
    sensorBudget,
    zones: newZones,
  };
}
